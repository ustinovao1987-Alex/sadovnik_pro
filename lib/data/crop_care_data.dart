        ];
    }
  }

  static List<String> _agroTips(CropRecord r) {
    final out = <String>[];
    if (r.sowDepth > 0) {
      out.add('Глубина заделки ${r.sowDepth} см, схема посадки ${r.scheme}.');
    } else {
      out.add('Схема посадки ${r.scheme}; сердечко не заглубляйте.');
    }
    out.add('Прорастание семян: почва от +${r.germinationTemp} °C.');
    out.add('Посадка/высадка: почва от +${r.plantingTemp} °C.');
    out.add(r.frostText);
    out.add('Освещение: ${r.light}.');
    out.add(
        'Семейство ${CropCatalog.familyTitle(r.family).toLowerCase()}: не возвращайте на эту грядку 3–4 года.');
    return out;
  }


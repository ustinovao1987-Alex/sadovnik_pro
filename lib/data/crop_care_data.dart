/// Журнал полива.
class WateringLog {
  static String _key(String cropKey) => 'water_last_$cropKey';

  static Future<DateTime?> last(String cropKey) async {
    final prefs = await SharedPreferences.getInstance();
    final ms = prefs.getInt(_key(cropKey));
    if (ms == null) return null;
    return DateTime.fromMillisecondsSinceEpoch(ms);
  }

  static Future<void> mark(String cropKey, DateTime t) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setInt(_key(cropKey), t.millisecondsSinceEpoch);
  }

  static Future<void> clear(String cropKey) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.remove(_key(cropKey));
  }

  static String sinceText(DateTime? last) {
    if (last == null) return 'Полив ещё не отмечен';
    final days = DateTime.now().difference(last).inDays;
    if (days == 0) return 'Полито сегодня';
    if (days == 1) return 'Полито вчера';
    return 'Полито $days дн. назад';
  }

  static bool isDue(DateTime? last, int everyDays) {
    if (last == null) return true;
    final gap = everyDays <= 0 ? 5 : everyDays;
    return DateTime.now().difference(last).inDays >= gap;
  }
}

/// Чек-лист приёмов ухода.
class CareChecklist {
  static String _key(String cropKey, int i) => 'care_tip_${cropKey}_$i';

  static Future<List<bool>> load(String cropKey, int count) async {
    final prefs = await SharedPreferences.getInstance();
    return List.generate(
        count, (i) => prefs.getBool(_key(cropKey, i)) ?? false);
  }

  static Future<void> set(String cropKey, int i, bool value) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(_key(cropKey, i), value);
  }

  static Future<void> reset(String cropKey, int count) async {
    final prefs = await SharedPreferences.getInstance();
    for (var i = 0; i < count; i++) {
      await prefs.remove(_key(cropKey, i));
    }
  }
}

enum ProblemKind { disease, pest }

enum DangerLevel { low, medium, high }

class CropProblem {
  final String name;
  final ProblemKind kind;
  final DangerLevel danger;
  final String symptoms;
  final List<String> treatment;
  final List<String> prevention;

  const CropProblem({
    required this.name,
    required this.kind,
    required this.danger,
    required this.symptoms,
    required this.treatment,
    required this.prevention,
  });
}

class CropCare {
  final String key;
  final String name;
  final String waterMethod;
  final String soil;
  final List<String> feeding;
  final List<String> tips;
  final List<CropProblem> problems;

  /// Заполняется расчётом FAO-56, а не константой.
  final int waterEveryDays;
  final String waterAmount;
  final IrrigationPlan? plan;
  final double plantAreaM2;

  const CropCare({
    required this.key,
    required this.name,
    required this.waterMethod,
    required this.soil,
    required this.feeding,
    required this.tips,
    required this.problems,
    this.waterEveryDays = 0,
    this.waterAmount = '',
    this.plan,
    this.plantAreaM2 = 0.25,
  });
}

class CropCareRepository {
  static CropCare forCrop(String cropName) {
    final rec = CropCatalog.byName(cropName);
    if (rec != null) {
      final manual = rec.careKey == null ? null : _byKey(rec.careKey!);
      final base = manual ?? _fromRecord(rec);
      return _withIrrigation(_enrich(base, rec), rec);
    }
    final n = cropName.toLowerCase().replaceAll('ё', 'е');
    for (final c in all) {
      if (n.contains(c.key)) return _withIrrigation(c, null);
    }
    return _withIrrigation(universal, null);
  }

  static CropCare? _byKey(String key) {
    for (final c in all) {
      if (c.key == key) return c;
    }
    return null;
  }

  // ---------- Полив: расчёт вместо констант ----------

  static CropCare _withIrrigation(CropCare base, CropRecord? r) {
    final area = r == null ? 0.25 : (r.spacing * r.rows) / 10000.0;
    final stage = r == null ? GrowthStage.mid : _stageFor(r);
    final plan = IrrigationAdvisor.planFor(
      cropId: r?.id ?? base.key,
      plantAreaM2: area,
      stage: stage,
    );
    return CropCare(
      key: base.key,
      name: base.name,
      waterMethod: base.waterMethod,
      soil: base.soil,
      feeding: base.feeding,
      tips: base.tips,
      problems: base.problems,
      waterEveryDays: plan.intervalDays,
      waterAmount: plan.rainCoversNeed
          ? 'Полив не нужен — достаточно дождя'
          : '${plan.litersPerPlant.toStringAsFixed(1)} л под растение '
              '(≈ ${plan.doseMm.toStringAsFixed(0)} л/м²)',
      plan: plan,
      plantAreaM2: area,
    );
  }

  /// Фаза роста из календаря культуры: от посева/высадки до уборки.
  static GrowthStage _stageFor(CropRecord r) {
    final now = DateTime.now();
    final cal = PlantingCalendarUtils.forCrop(r.name);
    if (cal == null) return GrowthStage.mid;
    DateTime? sow;
    DateTime? harvest;
    for (final s in cal.stages) {
      final d = DateTime(now.year, s.startMonth, s.startDay);
      if (s.isPlanting) {
        sow ??= d;
      } else {
        harvest ??= d;
      }
    }
    if (sow == null || harvest == null) return GrowthStage.mid;
    if (!now.isAfter(sow)) return GrowthStage.initial;
    final total = harvest.difference(sow).inDays;
    if (total <= 0) return GrowthStage.mid;
    final p = now.difference(sow).inDays / total;
    return IrrigationAdvisor.stageFromProgress(p.clamp(0.0, 1.0));
  }

  // ---------- Уход из агрономических параметров ----------

  static CropCare _fromRecord(CropRecord r) {
    return CropCare(
      key: r.id,
      name: r.name,
      waterMethod: _waterMethod(r),
      soil: r.soil,
      feeding: _feeding(r),
      tips: [...r.tips, ..._agroTips(r)],
      problems: _problems(r, const []),
    );
  }

  static CropCare _enrich(CropCare base, CropRecord r) {
    return CropCare(
      key: base.key,
      name: base.name,
      waterMethod: base.waterMethod,
      soil: base.soil,
      feeding: base.feeding,
      tips: base.tips,
      problems: _problems(r, base.problems),
    );
  }

  static List<CropProblem> _problems(CropRecord r, List<CropProblem> existing) {
    final seen = existing.map((p) => p.name.toLowerCase()).toSet();
    final out = <CropProblem>[...existing];
    for (final s in [...r.extra, ...FamilyProblems.of(r.family)]) {
      if (seen.add(s.name.toLowerCase())) out.add(_convert(s));
    }
    return out;
  }

  static CropProblem _convert(ProblemSpec s) => CropProblem(
        name: s.name,
        kind: s.disease ? ProblemKind.disease : ProblemKind.pest,
        danger: s.danger >= 3
            ? DangerLevel.high
            : (s.danger == 2 ? DangerLevel.medium : DangerLevel.low),
        symptoms: s.symptoms,
        treatment: s.treatment,
        prevention: s.prevention,
      );

  static String _waterMethod(CropRecord r) {
    final warm = r.frost == FrostTolerance.tender;
    final base = warm
        ? 'Поливайте тёплой водой (+20…25 °C) строго под корень, утром или после 17 часов. '
        : 'Поливайте под корень утром или вечером, не размывая почву. ';
    String note;
    switch (r.family) {
      case CropFamily.solanaceae:
        note = 'Листья должны оставаться сухими — иначе фитофтороз.';
        break;
      case CropFamily.cucurbitaceae:
        note =
            'Только тёплая вода: холодная вызывает корневые гнили и горечь плодов.';
        break;
      case CropFamily.brassicaceae:
        note =
            'Не допускайте пересыхания, но и не заливайте: переувлажнение провоцирует килу и гнили.';
        break;
      case CropFamily.apiaceae:
        note = 'Влажность равномерная — скачки дают треснувшие корнеплоды.';
        break;
      case CropFamily.amaryllidaceae:
        note =
            'За 2–3 недели до уборки полив прекратите, иначе шейка не вызреет.';
        break;
      case CropFamily.fabaceae:
        note =
            'Умеренно до цветения, обильно в налив бобов. Перелив даёт гнили.';
        break;
      case CropFamily.asteraceae:
        note = 'Часто и понемногу: пересыхание даёт горечь и стрелкование.';
        break;
      case CropFamily.amaranthaceae:
        note = 'Равномерный полив: скачки делают корнеплод волокнистым.';
        break;
      case CropFamily.poaceae:
        note = 'Критичен полив в цветение и налив початков.';
        break;
      case CropFamily.polygonaceae:
        note = 'Умеренно; после каждой срезки полейте и подкормите.';
        break;
      case CropFamily.lamiaceae:
        note = 'По подсыханию: пряные травы не терпят застоя воды.';
        break;
      case CropFamily.rosaceae:
        note = 'Под корень, чтобы ягоды не лежали на мокрой земле.';
        break;
    }
    return '$base$note';
  }

